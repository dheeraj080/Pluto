import type { ExpoConfig } from 'expo/config';

/**
 * Refuse to build a production binary that cannot talk to the API or sign anyone
 * in.
 *
 * `EXPO_PUBLIC_*` values are inlined at build time, so a slip here ships a
 * release that points at `localhost` — or has no Google client ID and therefore
 * no way to log in — and fails on the device with no visible cause. EAS sets
 * `EAS_BUILD_PROFILE` for the build in progress, so the check engages only on the
 * `production` profile and never during local `expo start` / `expo export`,
 * where no profile is set.
 *
 * The real values come from EAS environment variables scoped to the `production`
 * profile, not from a committed file.
 */
function assertProductionConfig(): void {
  if (process.env.EAS_BUILD_PROFILE !== 'production') return;

  const apiUrl = process.env.EXPO_PUBLIC_API_URL;
  const apiProblem = !apiUrl
    ? 'EXPO_PUBLIC_API_URL is not set'
    : !apiUrl.startsWith('https://')
      ? `EXPO_PUBLIC_API_URL must use https, got "${apiUrl}"`
      : /localhost|127\.0\.0\.1|10\.0\.2\.2/.test(apiUrl)
        ? `EXPO_PUBLIC_API_URL must not point at a development host, got "${apiUrl}"`
        : null;

  const clientIds = [
    ['EXPO_PUBLIC_GOOGLE_WEB_CLIENT_ID', process.env.EXPO_PUBLIC_GOOGLE_WEB_CLIENT_ID],
  ].filter(([, value]) => !value);

  if (apiProblem || clientIds.length > 0) {
    const problems = [
      ...(apiProblem ? [apiProblem] : []),
      ...clientIds.map(([name]) => `${name} is not set`),
    ];
    throw new Error(
      `[app.config] Production build refused: ${problems.join('; ')}. ` +
        'Set these as EAS environment variables on the production profile.',
    );
  }
}

/**
 * The reverse-DNS URL scheme iOS derives from an OAuth client ID.
 *
 * `1234-abc.apps.googleusercontent.com` becomes
 * `com.googleusercontent.apps.1234-abc`, which is the value the Google plugin
 * expects. Returns `null` for anything that is not an iOS client ID.
 */
function iosUrlScheme(clientId: string | undefined): string | null {
  const suffix = '.apps.googleusercontent.com';
  if (!clientId || !clientId.endsWith(suffix)) return null;
  return `com.googleusercontent.apps.${clientId.slice(0, -suffix.length)}`;
}

assertProductionConfig();

